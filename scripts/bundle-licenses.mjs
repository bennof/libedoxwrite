// Collect installed direct and transitive dependencies, including development tools.
import * as checker from 'license-checker-rseidelsohn';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const packages = await new Promise((resolve, reject) => checker.init({
  start: root,
  customFormat: { licenseText: '', copyright: '' },
}, (error, result) => error ? reject(error) : resolve(result)));
const report = {};
const missing = [];
for (const [name, info] of Object.entries(packages).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  if (name === `${manifest.name}@${manifest.version}`) continue;
  const texts = [];
  // Preserve additional notices as well as the primary license selected by the tool.
  if (info.path) {
    for (const entry of (await readdir(info.path, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
      if (entry.isFile() && /^(licen[cs]e|copying|copyright|notice|third[-_ ]?party.*notice)/i.test(entry.name)) {
        texts.push({ file: entry.name, text: await readFile(join(info.path, entry.name), 'utf8') });
      }
    }
  }
  if (!texts.length && info.licenseText?.trim()) texts.push({ file: 'License text detected by license-checker', text: info.licenseText });
  if (!texts.length || !info.licenses || /UNKNOWN|UNLICENSED/.test(String(info.licenses))) missing.push(name);
  report[name] = { licenses: info.licenses, repository: info.repository, publisher: info.publisher, copyright: info.copyright, texts };
}
if (!Object.keys(report).length && Object.keys(manifest.devDependencies ?? {}).length) throw new Error('No dependencies found. Run npm ci (including development dependencies) first.');
if (missing.length) throw new Error(`Missing license text or unresolved license: ${missing.join(', ')}`);
const header = 'THIRD-PARTY LICENSES\n\nInstalled direct and transitive npm dependencies, including development tools.\nPlatform-specific optional packages are included only when installed.\nGenerated by npm run licenses. Project code remains under LICENSE.\n';
const sections = Object.entries(report).map(([name, info]) => [
  '\n' + '='.repeat(80), name, `License: ${[].concat(info.licenses).join(' OR ')}`,
  info.repository ? `Repository: ${info.repository}` : '',
  ...info.texts.map(({ file, text }) => `\n--- ${file} ---\n${text}`),
].filter(Boolean).join('\n'));
await writeFile(join(root, 'THIRD-PARTY-LICENSES.txt'), header + sections.join('\n') + '\n');
await writeFile(join(root, 'THIRD-PARTY-LICENSES.json'), JSON.stringify(report, null, 2) + '\n');
console.log(`Bundled licenses and notices for ${Object.keys(report).length} installed packages.`);
